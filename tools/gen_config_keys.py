#!/usr/bin/env python3
"""Generate tools/config_keys.js (the config key reference shown by
tools/serial_setup.html) from the "| Key | Default | Description |" tables in
README.md, and check that every config key the firmware reads is documented.

    python3 tools/gen_config_keys.py           # rewrite tools/config_keys.js
    python3 tools/gen_config_keys.py --check   # CI: fail if stale or a key is undocumented

Keys the firmware reads are found in src/ and include/ as string literals in
get_value("k") / get_value<T>("k") / has_key("k"), `CFG_X[] = "k"` constants
and i2cAddr(ds, "k"). Keys built at run time (status_<N>_..., message_<name>_...)
are documented in the README with <placeholders>, which match any text.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
OUT = ROOT / "tools" / "config_keys.js"

CODE_PATTERNS = [
    re.compile(r'(?:get_value(?:<\w+>)?|has_key)\("([A-Za-z0-9_]+)"'),
    re.compile(r'CFG_[A-Z0-9_]+\[\]\s*=\s*"([a-z0-9_]+)"'),
    re.compile(r'i2cAddr\(ds,\s*"([a-z0-9_]+)"'),
]
# Prefixes of keys assembled at run time; their documented forms carry <...>.
DYNAMIC_PREFIXES = {"message_", "status_"}


def plain(md):
    """Markdown table cell -> plain text."""
    s = md.replace("\\|", "|")
    s = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", s)   # links
    s = s.replace("`", "")
    s = re.sub(r"\*\*?([^*]+)\*\*?", r"\1", s)        # bold / italics
    return s.strip()


def split_row(line):
    cells = re.split(r"(?<!\\)\|", line.strip())
    return [c.strip() for c in cells[1:-1]]


def readme_entries():
    entries, section, in_table = [], "", False
    for line in README.read_text(encoding="utf-8").splitlines():
        if line.startswith("#"):
            section = line.lstrip("#").strip()
            in_table = False
            continue
        if not line.startswith("|"):
            in_table = False
            continue
        cells = split_row(line)
        if not in_table:
            in_table = cells[:1] == ["Key"]
            continue
        if not cells or set(cells[0]) <= set("-: "):
            continue
        keys = re.findall(r"`([^`]+)`", cells[0])
        if not keys:
            continue
        entries.append({
            "keys": keys,
            "def": plain(cells[1]) if len(cells) > 1 else "",
            "desc": plain(cells[2]) if len(cells) > 2 else "",
            "section": section,
        })
    return entries


def render(entries):
    # One row per line keeps README edits readable in the diff.
    body = "[\n" + ",\n".join(" " + json.dumps(e, ensure_ascii=False) for e in entries) + "\n]"
    return ("// Generated by tools/gen_config_keys.py from the README.md key tables.\n"
            "// Do not edit: change README.md and rerun the script.\n"
            "window.CONFIG_KEYS = " + body + ";\n")


def code_keys():
    keys = set()
    for d in ("src", "include"):
        for p in (ROOT / d).rglob("*"):
            if p.suffix in {".cpp", ".hpp", ".h", ".c"}:
                text = p.read_text(encoding="utf-8", errors="replace")
                for pat in CODE_PATTERNS:
                    keys.update(pat.findall(text))
    return keys


def undocumented(entries):
    exact = {k for e in entries for k in e["keys"]}
    templates = [re.compile("^" + re.sub(r"<[^>]+>", ".+", re.escape(k).replace(r"\<", "<").replace(r"\>", ">")) + "$")
                 for k in exact if "<" in k]
    missing = []
    for k in sorted(code_keys()):
        if k in exact or k in DYNAMIC_PREFIXES or any(t.match(k) for t in templates):
            continue
        missing.append(k)
    return missing


def main():
    check = "--check" in sys.argv[1:]
    entries = readme_entries()
    text = render(entries)
    missing = undocumented(entries)
    if missing:
        print("Config keys read by the firmware but missing from the README key tables:")
        for k in missing:
            print("  " + k)
    if check:
        stale = not OUT.exists() or OUT.read_text(encoding="utf-8") != text
        if stale:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 tools/gen_config_keys.py")
        if stale or missing:
            sys.exit(1)
        print(f"config keys OK ({sum(len(e['keys']) for e in entries)} documented)")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(entries)} rows)")
    if missing:
        sys.exit(1)


if __name__ == "__main__":
    main()
